"""Write external/ffmpeg/build/sources.cmake: the C sources of libavutil and libavcodec that
FFmpeg's own build would compile for the configuration in external/ffmpeg/build (configure.bat).

FFmpeg builds with GNU make, which this toolchain lacks. This evaluates the subset of make the
library Makefiles use: VAR = / := / += (names and values with $(VAR) references), backslash
continuations, `include`, plus the per-arch Makefile and ffbuild/arch.mak, as Makefile's DOSUBDIR
does. Objects without a .c source (assembly) are dropped.

usage: python -I tools/ffmpeg/gen_sources.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "external" / "ffmpeg" / "FFmpeg-n7.1"
BUILD = ROOT / "external" / "ffmpeg" / "build"
# Compiled by runtime/src/xma_ffmpeg.c (it includes the file to reach its static functions).
SHIM_INCLUDED = {"libavcodec/wmaprodec.c"}

ASSIGN = re.compile(r"^([A-Za-z0-9_\-$().!]+)\s*(\+=|:=|=)\s*(.*)$")
REF = re.compile(r"\$\(([A-Za-z0-9_\-!]+)\)")


def expand(text, env):
    # Innermost first: names may themselves hold references (OBJS-$(CONFIG_X)).
    while True:
        new = REF.sub(lambda m: env.get(m.group(1), ""), text)
        if new == text:
            return new
        text = new


def logical_lines(path):
    lines, cur = [], ""
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.split("#", 1)[0] if not raw.lstrip().startswith("#") else ""
        if line.rstrip().endswith("\\"):
            cur += line.rstrip()[:-1] + " "
            continue
        lines.append(cur + line)
        cur = ""
    if cur:
        lines.append(cur)
    return lines


def run_makefile(path, env, optional=False):
    if not path.exists():
        if optional:
            return
        sys.exit(f"missing {path}")
    for line in logical_lines(path):
        s = line.strip()
        if not s:
            continue
        inc = re.match(r"^-?include\s+(.*)$", s)
        if inc:
            target = Path(expand(inc.group(1), env).strip())
            run_makefile(target, env, optional=s.startswith("-"))
            continue
        m = ASSIGN.match(s)
        if not m:
            continue  # rules, conditionals: not used by the object lists
        name, op, value = expand(m.group(1), env).strip(), m.group(2), expand(m.group(3), env).strip()
        if op == "+=":
            env[name] = (env.get(name, "") + " " + value).strip()
        else:
            env[name] = value


def config():
    env = {"SRC_PATH": SRC.as_posix()}
    for line in (BUILD / "ffbuild" / "config.mak").read_text().splitlines():
        m = re.match(r"^(!?[A-Za-z0-9_]+)=(.*)$", line)
        if m:
            env[m.group(1)] = m.group(2).strip()
    return env


def library_sources(lib, base):
    env = dict(base)
    for var in ("OBJS", "OBJS-yes"):
        env.pop(var, None)
    run_makefile(SRC / lib / "Makefile", env)
    run_makefile(SRC / lib / env.get("ARCH", "x86") / "Makefile", env, optional=True)
    if env.get("INTRINSICS"):
        run_makefile(SRC / lib / env["INTRINSICS"] / "Makefile", env, optional=True)
    run_makefile(SRC / "ffbuild" / "arch.mak", env)
    objs = set((env.get("OBJS", "") + " " + env.get("OBJS-yes", "")).split())
    sources = []
    for obj in sorted(objs):
        rel = f"{lib}/{obj[:-2]}.c"
        if obj.endswith(".o") and (SRC / rel).exists() and rel not in SHIM_INCLUDED:
            sources.append(rel)
    return sources


def main():
    base = config()
    out = ["# Generated by tools/ffmpeg/gen_sources.py. Do not edit."]
    for lib, var in (("libavutil", "FFMPEG_AVUTIL_SOURCES"), ("libavcodec", "FFMPEG_AVCODEC_SOURCES")):
        sources = library_sources(lib, base)
        out.append(f"set({var}")
        out += [f'    "${{FFMPEG_SRC}}/{s}"' for s in sources]
        out.append(")")
        print(f"{lib}: {len(sources)} sources")
    (BUILD / "sources.cmake").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
