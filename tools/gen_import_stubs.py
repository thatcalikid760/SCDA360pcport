"""Generate runtime/src/imports_stubs.cpp: a logging stub for every import in
generated/ppc_recomp_shared.h that no runtime/src/*.cpp implements.

usage: python -I tools/gen_import_stubs.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    shared = (ROOT / "generated" / "ppc_recomp_shared.h").read_text()
    imports = re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);", shared)
    done = set()
    for src in (ROOT / "runtime" / "src").glob("*.cpp"):
        if src.name != "imports_stubs.cpp":
            done |= set(re.findall(r"SCDA_IMPORT\((\w+)\)", src.read_text()))
    stubs = [n for n in imports if n not in done and not n.startswith("sub_")]
    lines = ["// Generated by tools/gen_import_stubs.py. Do not edit: implement in imports.cpp instead.",
             "#include <runtime.h>", ""]
    lines += [f'SCDA_IMPORT({n}) {{ ImportStub("{n}", ctx); }}' for n in stubs]
    (ROOT / "runtime" / "src" / "imports_stubs.cpp").write_text("\n".join(lines) + "\n")
    print(f"{len(imports)} imports, {len(done)} implemented, {len(stubs)} stubbed")


if __name__ == "__main__":
    main()
