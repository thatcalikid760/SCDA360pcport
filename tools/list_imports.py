"""List XEX import records (library, ordinal, name, type, kind, record VA).

Header comes from the raw XEX (headers are not encrypted); record values come
from the decrypted flat image (tools/xex_dump). Writes:
  docs/imports_<name>.txt            all records
  runtime/src/import_vars.inc        X(lib, ordinal, name, record_va) for variable exports

usage: python -I tools/list_imports.py assets/SC4_Offline.xex assets/SC4_Offline.bin
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "external" / "XenonRecomp" / "XenonUtils" / "xbox"
BASE = 0x82000000
CODE_BASE = 0x821A0000
XEX_HEADER_IMPORT_LIBRARIES = 0x000103FF


def load_table(path):
    out = {}
    for ordinal, name, kind in re.findall(r"XE_EXPORT\(\w+,\s*0x([0-9A-Fa-f]+),\s*(\w+),\s*(\w+)\)", path.read_text()):
        out[int(ordinal, 16)] = (name, kind)
    return out


def main():
    xex = Path(sys.argv[1]).read_bytes()
    img = Path(sys.argv[2]).read_bytes()
    tables = {"xboxkrnl.exe": load_table(TABLES / "xboxkrnl_table.inc"), "xam.xex": load_table(TABLES / "xam_table.inc")}

    count = struct.unpack_from(">I", xex, 0x14)[0]
    off = None
    for i in range(count):
        key, val = struct.unpack_from(">II", xex, 0x18 + i * 8)
        if key == XEX_HEADER_IMPORT_LIBRARIES:
            off = val
    assert off is not None, "no import header"

    _, str_size, num = struct.unpack_from(">III", xex, off)
    names, p = [], off + 12
    for _ in range(num):
        end = xex.index(b"\0", p)
        names.append(xex[p:end].decode())
        p += ((end - p + 1) + 3) & ~3
    lib = off + 12 + str_size

    rows, variables = [], []
    for libname in names:
        size = struct.unpack_from(">I", xex, lib)[0]
        nimp = struct.unpack_from(">H", xex, lib + 0x26)[0]
        table = tables.get(libname, {})
        for i in range(nimp):
            va = struct.unpack_from(">I", xex, lib + 0x28 + i * 4)[0]
            if va >= CODE_BASE:
                continue  # thunk: XenonUtils overwrote it with nop/blr; the IAT record carries the info
            # XenonUtils byte-swaps IAT records in place, so the dumped value is little-endian.
            val = struct.unpack_from("<I", img, va - BASE)[0]
            rtype, ordinal = val >> 24, val & 0xFFFF
            name, kind = table.get(ordinal, (f"ord_{ordinal:X}", "?"))
            rows.append(f"{libname:13} 0x{ordinal:03X} type={rtype} {kind:10} 0x{va:08X} {name}")
            if rtype == 0 and kind == "kVariable":
                variables.append(f'X("{libname}", 0x{ordinal:03X}, {name}, 0x{va:08X})')
        lib += size

    stem = Path(sys.argv[1]).stem
    (ROOT / "docs" / f"imports_{stem}.txt").write_text("\n".join(rows) + "\n")
    (ROOT / "runtime" / "src" / "import_vars.inc").write_text(
        "// Generated by tools/list_imports.py. X(library, ordinal, name, record VA)\n" + "\n".join(variables) + "\n")
    print(f"{len(rows)} records, {len(variables)} variable imports")


if __name__ == "__main__":
    main()
